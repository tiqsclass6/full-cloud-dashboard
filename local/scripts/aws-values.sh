#!/usr/bin/env bash
# Write the git-ignored account-specific values from Terraform outputs (pushed only to the cluster's Gitea).
#   usage: aws-values.sh [env]     (default dev)
ENV_NAME="${1:-dev}"
GITOPS_ENV="${ENV_NAME}" KUBE_CONTEXT="lakehouse-${ENV_NAME}"
export GITOPS_ENV KUBE_CONTEXT
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
require terraform aws

TF_DIR="${REPO_ROOT}/terraform/envs/${ENV_NAME}"
tfout() { terraform -chdir="${TF_DIR}" output -raw "$1"; }

REGISTRY="$(tfout ecr_registry)"
WAREHOUSE="$(tfout warehouse)"
CHECKPOINTS="$(tfout checkpoints_bucket)"
POSTGRES="$(tfout postgres_endpoint)"
FLINK_ROLE="$(tfout flink_jobs_role_arn)"
ESO_ROLE="$(tfout external_secrets_role_arn)"
PG_SECRET="$(tfout postgres_secret_arn)"
GRAFANA_SECRET="$(tfout grafana_admin_secret_name)"
SPARK_ROLE="$(tfout spark_jobs_role_arn)"
KYVERNO_ROLE="$(tfout kyverno_admission_role_arn)"
EXPORTER_ROLE="$(tfout iceberg_exporter_role_arn)"
REGION="$(tfout region)"
CLUSTER="$(tfout cluster_name)"
OPS_AGENT_ROLE="$(tfout ops_agent_role_arn)"
HERMES_ROLE="$(tfout hermes_role_arn)"
LBC_ROLE="$(tfout aws_load_balancer_controller_role_arn)"
VPC_ID="$(tfout vpc_id)"
VPC_CIDR="$(tfout vpc_cidr)"
RUNTIME_ARN="$(tfout agentcore_runtime_arn)"     # empty until the second apply (agentcore_runtime = true)
# The image-signing public key (the private key never leaves KMS), as PEM indented for the YAML below.
SIGNING_KEY_ID="$(tfout image_signing_key)"; SIGNING_KEY_ID="${SIGNING_KEY_ID#awskms:///}"
PUBLIC_KEY="$( { echo "-----BEGIN PUBLIC KEY-----"
  aws kms get-public-key --region "${REGION}" --key-id "${SIGNING_KEY_ID}" --query PublicKey --output text | fold -w 64
  echo "-----END PUBLIC KEY-----"; } | sed 's/^/        /')"
HEADER="# Generated by local/scripts/aws-values.sh from terraform/envs/${ENV_NAME} outputs. Do not edit (git-ignored)."

mkdir -p "${REPO_ROOT}/helm/values/generated"
cat > "${REPO_ROOT}/helm/values/generated/${ENV_NAME}.yaml" <<EOF
${HEADER}
global:
  imageRegistry: ${REGISTRY}
  iceberg:
    warehouse: ${WAREHOUSE}
schema-registry:
  datasource:
    # TLS required (the RDS parameter group also refuses non-TLS connections).
    url: jdbc:postgresql://${POSTGRES}:5432/apicurio?sslmode=require
secrets:
  externalSecrets:
    schema-registry-db:
      remoteKey: ${PG_SECRET}
    grafana-admin:
      remoteKey: ${GRAFANA_SECRET}
    ops-control-db:
      remoteKey: ${PG_SECRET}
policies:
  validation:
    extraAllowedImagePrefixes: ["${REGISTRY}/lakehouse/"]
  imageVerification:
    enabled: true
    imageGlob: "${REGISTRY}/lakehouse/*"
    publicKey: |
${PUBLIC_KEY}
iceberg-exporter:
  serviceAccount:
    annotations:
      eks.amazonaws.com/role-arn: ${EXPORTER_ROLE}
flink-jobs:
  storage:
    checkpointsDir: s3://${CHECKPOINTS}/flink/checkpoints
    savepointsDir: s3://${CHECKPOINTS}/flink/savepoints
  highAvailability:
    storageDir: s3://${CHECKPOINTS}/flink/ha
ai-ops:
  database:
    host: ${POSTGRES}
  agent:
    serviceAccount:
      annotations:
        eks.amazonaws.com/role-arn: ${OPS_AGENT_ROLE}
    agentcore:
      runtimeArn: "${RUNTIME_ARN}"
  hermes:
    serviceAccount:
      annotations:
        eks.amazonaws.com/role-arn: ${HERMES_ROLE}
  mcp:
    vpcEndpoint:
      allowedCidr: ${VPC_CIDR}
EOF
ok "helm/values/generated/${ENV_NAME}.yaml"

cat > "${REPO_ROOT}/gitops/operators/flink-operator/generated-${ENV_NAME}.yaml" <<EOF
${HEADER}
jobServiceAccount:
  annotations:
    "helm.sh/resource-policy": keep
    eks.amazonaws.com/role-arn: ${FLINK_ROLE}
EOF
ok "gitops/operators/flink-operator/generated-${ENV_NAME}.yaml"

cat > "${REPO_ROOT}/gitops/operators/external-secrets/generated-${ENV_NAME}.yaml" <<EOF
${HEADER}
serviceAccount:
  annotations:
    eks.amazonaws.com/role-arn: ${ESO_ROLE}
EOF
ok "gitops/operators/external-secrets/generated-${ENV_NAME}.yaml"

cat > "${REPO_ROOT}/gitops/operators/spark-operator/generated-${ENV_NAME}.yaml" <<EOF
${HEADER}
spark:
  serviceAccount:
    annotations:
      eks.amazonaws.com/role-arn: ${SPARK_ROLE}
EOF
ok "gitops/operators/spark-operator/generated-${ENV_NAME}.yaml"

cat > "${REPO_ROOT}/gitops/operators/kyverno/generated-${ENV_NAME}.yaml" <<EOF
${HEADER}
admissionController:
  rbac:
    serviceAccount:
      annotations:
        eks.amazonaws.com/role-arn: ${KYVERNO_ROLE}
EOF
ok "gitops/operators/kyverno/generated-${ENV_NAME}.yaml"

cat > "${REPO_ROOT}/gitops/operators/aws-load-balancer-controller/generated-${ENV_NAME}.yaml" <<EOF
${HEADER}
clusterName: ${CLUSTER}
region: ${REGION}
vpcId: ${VPC_ID}
serviceAccount:
  annotations:
    eks.amazonaws.com/role-arn: ${LBC_ROLE}
EOF
ok "gitops/operators/aws-load-balancer-controller/generated-${ENV_NAME}.yaml"
